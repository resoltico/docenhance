"""Generate the concrete implemented methods' parameter records and primitive validation."""

from __future__ import annotations

from typing import Any

from parameter_cpp import option_id
from parameter_values import INTEGER, NUMERIC, invalid

# C++ implementation names are code ownership, not capability admission. A new method needs an
# actual implementation and an explicit generator mapping; editing JSON cannot create one.
TYPES = {
    "I01": "SurfaceParameters",
    "I02": "MorphologyParameters",
    "D01": "NlmParameters",
    "D02": "Tvl1Parameters",
    "R01": "WienerParameters",
    "C01": "LevelsParameters",
    "C02": "GammaParameters",
    "C03": "ClaheParameters",
    "S01": "UnsharpParameters",
    "B01": "OtsuParameters",
    "B02": "SauvolaParameters",
    "B03": "FixedThresholdParameters",
}
PSF_TYPES = (("gaussian", "GaussianPsf"), ("motion", "MotionPsf"), ("kernel", "FilePsf"))
PREAMBLE = (
    "// SPDX-FileCopyrightText: 2026 Ervins Strauhmanis\n"
    "// SPDX-License-Identifier: MPL-2.0\n"
    "// Generated by tools/generate_spec.py from spec/method-contract.json.\n"
    "#pragma once\n"
    '#include "docenhance/core/utf8.hpp"\n'
    '#include "docenhance/methods/parameter_domains.hpp"\n'
    "#include <cstdint>\n#include <optional>\n#include <string>\n#include <variant>\n"
    "namespace docenhance::methods {\n"
    "enum class SurfaceMode { explicit_surface, automatic };\n"
)


def primitive_fields(option: dict[str, Any]) -> tuple[str, list[str]]:
    """Return typed member declarations and their corresponding domain checks."""
    kind, field, identity = option["kind"], option["field"], option_id(option)
    if kind in NUMERIC and "default" not in option:
        invalid(f"{option['name']}: numeric member has no supported typed default")
    if kind == "grid":
        declarations, checks = [], []
        for suffix in ("columns", "rows"):
            member = f"{field}_{suffix}"
            domain = f"{identity}_{suffix}_domain"
            declarations.append(f"    std::uint32_t {member} = {domain}.default_value;\n")
            checks.append(f"{domain}.contains(p.{member})")
        return "".join(declarations), checks
    type_name = "std::uint32_t" if kind in INTEGER else "double"
    domain = identity + "_domain"
    if kind in {"auto_or_integer", "source_or_decimal"}:
        declaration = f"    std::optional<{type_name}> {field} = {domain}.default_value;\n"
        return declaration, [f"(!p.{field} || {domain}.contains(*p.{field}))"]
    if kind == "path":
        return f"    std::string {field};\n", [f"core::valid_path(p.{field})"]
    if kind == "choice":
        invalid(f"Choice {option['name']} requires its concrete discriminated parameter type")
    return (
        f"    {type_name} {field} = {domain}.default_value;\n",
        [f"{domain}.contains(p.{field})"],
    )


def render_struct(name: str, options: list[dict[str, Any]], *, surface: bool = False) -> str:
    """Keep reusable primitive checks beside the generated raw factory-input record."""
    text, checks = f"struct {name} {{\n", []
    if surface:
        text += "    SurfaceMode mode = SurfaceMode::explicit_surface;\n"
        checks.append(
            "(p.mode == SurfaceMode::explicit_surface || p.mode == SurfaceMode::automatic)"
        )
    for option in options:
        declaration, predicates = primitive_fields(option)
        text += declaration
        checks.extend(predicates)
    text += f"    bool operator==(const {name}&) const = default;\n}};\n"
    parameter = "p" if checks else "/*p*/"
    text += f"[[nodiscard]] inline bool valid_parameters(const {name}& {parameter}) noexcept {{\n"
    text += "    return " + (" &&\n           ".join(checks) if checks else "true") + ";\n}\n"
    return text


def render_psf(parameters: list[dict[str, Any]], by_name: dict[str, dict[str, Any]]) -> str:
    """Represent conditional PSF fields by the existing closed C++ alternatives."""
    options = [by_name[parameter["option"]] for parameter in parameters]
    groups = psf_groups(options)
    text = ""
    for spelling, type_name in PSF_TYPES:
        text += render_struct(type_name, psf_members(spelling, groups[spelling]))
    text += "using Psf = std::variant<GaussianPsf, MotionPsf, FilePsf>;\n"
    text += "struct WienerParameters {\n    Psf psf = GaussianPsf{};\n"
    checks = []
    for option in groups["common"]:
        declaration, predicates = primitive_fields(option)
        text += declaration
        checks.extend(predicates)
    text += "    bool operator==(const WienerParameters&) const = default;\n};\n"
    text += "[[nodiscard]] inline bool valid_parameters(const WienerParameters& p) noexcept {\n"
    text += "    if (p.psf.valueless_by_exception()) { return false; }\n"
    text += "    if (!(" + (" && ".join(checks) or "true") + ")) { return false; }\n"
    for _, type_name in PSF_TYPES:
        text += (
            f"    if (const auto* const psf = std::get_if<{type_name}>(&p.psf)) {{\n"
            "        return valid_parameters(*psf);\n    }\n"
        )
    text += "    return false;\n}\n"
    return text


def psf_members(spelling: str, fields: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """The existing v14 FilePsf record retains its path member until the WP3 wire break."""
    return [{**field, "field": "path"} for field in fields] if spelling == "kernel" else fields


def psf_groups(options: list[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    """Account for every declared PSF member, refusing conditions this type cannot express."""
    groups: dict[str, list[dict[str, Any]]] = {
        name: [] for name in ("choice", "common", "gaussian", "motion", "kernel")
    }
    for option in options:
        when = option.get("when", {})
        if option["name"] == "--psf" and not when:
            group = "choice"
        elif not when:
            group = "common"
        else:
            group = when.get("--psf")
            if (
                group not in {"gaussian", "motion", "kernel"}
                or set(when) - {"--psf", "--deblur"}
                or when.get("--deblur", "wiener") != "wiener"
            ):
                invalid(f"{option['name']}: unsupported concrete PSF condition")
        groups[group].append(option)
    if len(groups["choice"]) != 1:
        invalid("R01 requires exactly one declared PSF discriminant")
    accounted = [option["name"] for group in groups.values() for option in group]
    if len(accounted) != len(options) or len(set(accounted)) != len(options):
        invalid("Each declared PSF parameter must be accounted for exactly once")
    return groups


def render_parameters(families: list[dict[str, Any]], options: list[dict[str, Any]]) -> str:
    """Emit each current concrete parameter type; cross-field method rules remain handwritten."""
    by_name = {option["name"]: option for option in options}
    text = PREAMBLE
    for family in families:
        for method in family["methods"]:
            if method["id"] not in TYPES:
                invalid(f"{method['id']}: no concrete C++ parameter owner")
            if method["id"] == "R01":
                text += render_psf(method["parameters"], by_name)
                continue
            # Preserve the existing named factory records, including their aggregate field order.
            own, shared = method["parameters"], family["shared"]
            fields = [*shared, *own] if family["family"] == "illumination" else [*own, *shared]
            if any(field.get("when") for field in fields):
                invalid(f"{method['id']}: unsupported conditional member in its concrete record")
            text += render_struct(
                TYPES[method["id"]],
                [by_name[field["option"]] for field in fields],
                surface=method["id"] == "I01",
            )
    return text + "} // namespace docenhance::methods\n"
