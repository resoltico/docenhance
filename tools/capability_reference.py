"""Derived capability descriptions, distinct from command syntax and executable metadata."""

from __future__ import annotations

from typing import Any

from method_metadata import support_matrix

METHODS_PREAMBLE = (
    "# Methods\n\n"
    "> Generated from `spec/method-contract.json` by `tools/generate_spec.py`. "
    "Only **implemented-selectable** methods appear in `docenhance methods`. "
    "**Implemented-automatic** capabilities run as built-in behavior without a selector. "
    "**Planned** methods require complete contracts, tests and fixtures.\n\n"
)


def render_methods(methods: list[dict[str, Any]]) -> str:
    """Render docs/methods.md."""
    text = METHODS_PREAMBLE
    for method in methods:
        text += f"## {method['id']} — {method['name']}\n\n"
        text += f"Classification: **{method['classification']}**.\n\n"
        if method["classification"] == "implemented-automatic":
            text += (
                "Automatic continuous metadata orientation; binary output ignores orientation.\n"
            )
            text += "No standalone selector or method-specific arguments.\n\n"
            continue
        references = ", ".join(f"`{x}`" for x in method.get("arguments", []))
        references = references or "See geometry/common options in the target contract"
        text += f"Method-specific argument references: {references}.\n\n"
    return text.rstrip() + "\n"


def render_roadmap(contract: dict[str, Any], methods: list[dict[str, Any]]) -> str:
    """Derive completed and future capability inventory from reviewed admission authorities."""
    text = (
        "# Capability roadmap\n\n> Generated by `tools/generate_spec.py` "
        "from reviewed method and CLI contracts.\n\n"
    )
    text += "## Completed capabilities\n\n"
    for item in support_matrix(contract["input_support"]):
        text += f"- `{item['format']}` input: {', '.join(item['output_modes'])}.\n"
    for method in methods:
        if method["classification"] != "planned":
            text += f"- {method['id']}: {method['name']} ({method['classification']}).\n"
    text += "\n## Active validation\n\n"
    text += (
        "Execution evidence is commit-specific. See [status](status.md), "
        "[foundation review](foundation-qa.md) and [quality evaluation](document-quality.md). "
        "Minimum-OS runtime, observed resource envelopes and cleared held-out human review "
        "are separate from numerical correctness. No empirical benefit is implied.\n"
    )
    text += "\n## Future capabilities\n\n"
    for method in methods:
        if method["classification"] == "planned":
            text += f"- {method['id']}: {method['name']}; no runtime selector admitted.\n"
    text += (
        "- Multipage processing, batch, presets and arbitrarily large streaming need separate "
        "complete contracts. No runtime OCR, neural/GPU, GUI or network component is planned.\n\n"
        "Future geometry follows the [A-F frame contract](geometry.md): one non-orthogonal "
        "full-resolution resampling, explicit protection footprints, density validity and "
        "abstention. Cataloging a method does not implement it.\n"
    )
    return text
