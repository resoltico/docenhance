"""Generate application-owned option identities and structured admission metadata."""

from __future__ import annotations

import json
from typing import Any

from parameter_cpp import numeric_literal, option_id
from parameter_values import NUMERIC, invalid

VOCABULARY = """class CommandSet {
  public:
    constexpr CommandSet() noexcept = default;
    template <typename... Commands>
    constexpr explicit CommandSet(Commands... commands) noexcept
        : bits_((0U | ... | bit(commands))) {}
    [[nodiscard]] constexpr bool contains(Command command) const noexcept {
        return (bits_ & bit(command)) != 0U;
    }
    [[nodiscard]] static constexpr CommandSet all() noexcept {
        CommandSet set;
        set.bits_ = (1U << command_count) - 1U;
        return set;
    }
  private:
    [[nodiscard]] static constexpr unsigned bit(Command command) noexcept {
        const auto index = static_cast<unsigned>(command);
        return index < command_count ? 1U << index : 0U;
    }
    unsigned bits_ = 0;
};
struct InputSupport { std::string_view format; bool binary; };
enum class ValueKind {
    flag, path, choice, decimal, integer, odd_integer,
    auto_or_integer, source_or_decimal, grid,
};
struct OptionCondition { OptionId option; std::string_view value; };
struct OperandBounds { std::size_t minimum; std::size_t maximum; };
struct OptionDescriptor {
    OptionId id;
    std::string_view name;
    std::string_view metavar;
    CommandSet scope;
    std::string_view group;
    std::string_view domain;
    std::string_view methods;
    std::string_view description;
    ValueKind kind;
    std::optional<std::string_view> default_value;
    bool required;
    bool selector;
    std::string_view family;
    std::span<const std::string_view> method_ids;
    std::span<const std::string_view> applies_to;
    std::span<const std::string_view> choices;
    std::span<const OptionCondition> when;
    double minimum;
    double maximum;
};
"""


def string_list(values: list[str], arrays: dict[tuple[str, ...], str]) -> str:
    """Intern immutable generated spelling sets, keeping the public header bounded."""
    if not values:
        return "{}"
    key = tuple(values)
    if key not in arrays:
        arrays[key] = f"option_strings_{len(arrays)}"
    return arrays[key]


def numeric_bounds(option: dict[str, Any]) -> tuple[str, str]:
    """Method domains reuse the actual typed primitive authority rather than new literals."""
    if option["kind"] not in NUMERIC:
        return "0", "0"
    if option["family"]:
        suffix = "_columns" if option["kind"] == "grid" else ""
        name = f"methods::{option_id(option)}{suffix}_domain"
        return f"{name}.minimum", f"{name}.maximum"
    return (
        numeric_literal(option["min"], integer=False),
        numeric_literal(option["max"], integer=False),
    )


def option_row(option: dict[str, Any], arrays: dict[tuple[str, ...], str]) -> str:
    """Render one fully structured option; no Invocation member pointers or owning data."""
    identity = option_id(option)
    low, high = numeric_bounds(option)
    scope = ", ".join("Command::" + command for command in option["scope"])
    fields = {
        "id": f"OptionId::{identity}",
        "name": json.dumps(option["name"]),
        "metavar": json.dumps(option["metavar"]),
        "scope": f"CommandSet{{{scope}}}",
        "group": json.dumps(option["group"]),
        "domain": json.dumps(option["domain"]),
        "methods": json.dumps(",".join(option["methods"])),
        "description": json.dumps(option["summary"]),
        "kind": f"ValueKind::{option['kind']}",
        "default_value": (
            f"std::string_view{{{json.dumps(option['default'])}}}"
            if "default" in option
            else "std::nullopt"
        ),
        "required": str(option.get("required", False)).lower(),
        "selector": str("selector_methods" in option).lower(),
        "family": json.dumps(option["family"]),
        "method_ids": string_list(option["methods"], arrays),
        "applies_to": string_list(option.get("applies_to", []), arrays),
        "choices": string_list(option.get("values", []), arrays),
        "when": identity + "_conditions" if option.get("when") else "{}",
        "minimum": low,
        "maximum": high,
    }
    return "    {" + ", ".join(f".{key} = {value}" for key, value in fields.items()) + "},\n"


def render_options(cli: dict[str, Any], options: list[dict[str, Any]]) -> str:
    """Declare command/option vocabulary without depending on raw Invocation storage."""
    text = (
        "// SPDX-FileCopyrightText: 2026 Ervins Strauhmanis\n"
        "// SPDX-License-Identifier: MPL-2.0\n"
        "// Generated by tools/generate_spec.py from the reviewed CLI/method contracts.\n"
        "#pragma once\n"
        '#include "docenhance/methods/parameter_domains.hpp"\n'
        "#include <array>\n#include <cstddef>\n#include <optional>\n#include <span>\n"
        "#include <string_view>\nnamespace docenhance::app {\n"
    )
    text += "enum class Command : unsigned { " + ", ".join(cli["commands"]) + " };\n"
    text += f"inline constexpr unsigned command_count = {len(cli['commands'])};\n"
    text += "enum class OptionId {\n" + "".join(f"    {option_id(o)},\n" for o in options)
    text += "    count_sentinel,\n};\n"
    text += (
        "inline constexpr auto option_count = static_cast<std::size_t>(OptionId::count_sentinel);\n"
    )
    text += VOCABULARY
    for function, key in (("command_name", None), ("command_usage", "usage")):
        text += f"[[nodiscard]] constexpr std::string_view {function}(Command c) noexcept {{\n"
        text += "    switch (c) {\n"
        for name, command in cli["commands"].items():
            text += (
                f"    case Command::{name}: return {json.dumps(command[key] if key else name)};\n"
            )
        text += "    }\n    return {};\n}\n"
    text += "[[nodiscard]] constexpr OperandBounds command_operands(Command c) noexcept {\n"
    text += "    switch (c) {\n"
    operand_groups: dict[tuple[int, int], list[str]] = {}
    for name, command in cli["commands"].items():
        bounds = command["operands"]
        low, high = (bounds, bounds) if type(bounds) is int else bounds
        operand_groups.setdefault((low, high), []).append(name)
    for (low, high), commands in operand_groups.items():
        text += "".join(f"    case Command::{name}:\n" for name in commands)
        text += f"        return {{.minimum = {low}U, .maximum = {high}U,}};\n"
    text += "    }\n    return {};\n}\n"
    arrays: dict[tuple[str, ...], str] = {}
    rows = "".join(option_row(option, arrays) for option in options)
    text += "// clang-format off\n"
    for values, name in arrays.items():
        text += f"inline constexpr auto {name} = std::to_array<std::string_view>({{"
        text += ", ".join(json.dumps(value) for value in values) + "});\n"
    for option in options:
        if option.get("when"):
            text += f"inline constexpr auto {option_id(option)}_conditions = "
            text += "std::to_array<OptionCondition>({"
            text += (
                ", ".join(
                    f"{{.option = OptionId::{name[2:].replace('-', '_')}, "
                    f".value = {json.dumps(value)}}}"
                    for name, value in option["when"].items()
                )
                + "});\n"
            )
    text += "inline constexpr auto option_catalog = std::to_array<OptionDescriptor>({\n" + rows
    text += "});\ninline constexpr auto input_support = std::to_array<InputSupport>({\n"
    for item in cli["formats"]:
        text += (
            f"    {{.format = {json.dumps(item['format'])}, "
            f".binary = {str('bw' in item['modes']).lower()}}},\n"
        )
    return text + "});\n// clang-format on\n} // namespace docenhance::app\n"


def render_execution_limits(options: list[dict[str, Any]]) -> str:
    """Derive common execution domains/defaults from the same admitted CLI declarations."""
    selected = {
        item["name"]: item for item in options if item["name"] in {"--threads", "--memory-limit"}
    }
    if set(selected) != {"--threads", "--memory-limit"}:
        invalid("Execution controls require both reviewed CLI declarations")
    threads, memory = selected["--threads"], selected["--memory-limit"]
    for item, kind in ((threads, "auto_or_integer"), (memory, "integer")):
        if (
            item["kind"] != kind
            or item["scope"] != ["process"]
            or item["family"]
            or "default" not in item
        ):
            invalid("Execution controls require process-only numeric defaults")
    default_threads = (
        "std::nullopt"
        if threads["default"] == "auto"
        else numeric_literal(threads["default"], integer=True)
    )
    thread_min = numeric_literal(threads["min"], integer=True)
    thread_max = numeric_literal(threads["max"], integer=True)
    memory_min = numeric_literal(memory["min"], integer=True)
    memory_max = numeric_literal(memory["max"], integer=True)
    memory_default = numeric_literal(memory["default"], integer=True)
    return (
        "// SPDX-FileCopyrightText: 2026 Ervins Strauhmanis\n"
        "// SPDX-License-Identifier: MPL-2.0\n"
        "// Generated by tools/generate_spec.py from spec/cli-contract.json.\n"
        "#pragma once\n#include <cstddef>\n#include <cstdint>\n#include <optional>\n\n"
        "namespace docenhance::core {\n"
        f"inline constexpr unsigned min_execution_threads = {thread_min};\n"
        f"inline constexpr unsigned max_execution_threads = {thread_max};\n"
        f"inline constexpr std::optional<unsigned> default_execution_threads = {default_threads};\n"
        f"inline constexpr std::uint64_t min_memory_limit_mib = {memory_min};\n"
        f"inline constexpr std::uint64_t max_memory_limit_mib = {memory_max};\n"
        "inline constexpr std::size_t default_memory_limit = "
        f"std::size_t{{{memory_default}}} * 1024 * 1024;\n"
        "} // namespace docenhance::core\n"
    )
